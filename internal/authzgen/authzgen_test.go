func TestRender_NameCollisionIsRefused(t *testing.T) {
	c := widget(t)
	c.Assembly.Permissions = append(c.Assembly.Permissions, component.Permission{Key: "conformance.widget.widget", Type: "action"})
	if _, err := Render(c, Go, Options{}); err == nil {
		t.Error("a key and a type with one constant name must be refused")
	}
}

func TestDetect_LanguageAndDefaultPath(t *testing.T) {
	dir := t.TempDir()
	if _, _, err := Detect(dir); err == nil {
		t.Error("no language marker: want an error")
	}
	testfixture.Write(t, dir, "backend/go.mod", "module x\n")
	lang, path, err := Detect(dir)
	if err != nil || lang != Go || path != filepath.Join(dir, "backend/internal/authzgen/authzgen.go") {
		t.Errorf("go = %v %s %v", lang, path, err)
	}
	py := t.TempDir()
	testfixture.Write(t, py, "pyproject.toml", "")
	if lang, path, _ := Detect(py); lang != Python || path != filepath.Join(py, "backend/app/authzgen.py") {
		t.Errorf("python = %v %s", lang, path)
	}
	ts := t.TempDir()
	testfixture.Write(t, ts, "package.json", "{}")
	if lang, path, _ := Detect(ts); lang != TypeScript || path != filepath.Join(ts, "src/authzgen.ts") {
		t.Errorf("ts = %v %s", lang, path)
	}
	if lang, err := LangOf("x/authzgen.py"); err != nil || lang != Python {
		t.Errorf("LangOf .py = %v %v", lang, err)
	}
}
