func TestRender_GoIsValidAndTyped(t *testing.T) {
	src, err := Render(widget(t), Go, Options{})
	if err != nil {
		t.Fatal(err)
	}
	s := string(src)
	for _, want := range []string{
		"// Code generated by be-ops authzgen", "DO NOT EDIT.", "package authzgen",
		`besdk "github.com/brickKit/be-sdk-go"`,
		`"view_key": "conformance.widget.view"`, `"delegable": false`, `"set": "conformance.widget.price"`,
	} {
		if !strings.Contains(s, want) {
			t.Errorf("Go output lacks %q:\n%s", want, s)
		}
	}
	for _, re := range []string{`WidgetView\s+besdk\.PermKey\s+= "conformance\.widget\.view"`,
		`WidgetPriceRead\s+besdk\.PermKey\s+= "conformance\.widget\.price\.read"`,
		`WidgetWidget\s+besdk\.ResourceType\s+= "conformance\.widget\.widget"`} {
		if !regexp.MustCompile(re).MatchString(s) {
			t.Errorf("Go output lacks %s (gofmt alignment allowed)", re)
		}
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "authzgen.go", src, 0); err != nil {
		t.Errorf("not valid Go: %v", err)
	}
	again, _ := Render(widget(t), Go, Options{})
	if string(again) != s {
		t.Error("not deterministic")
	}
}

func TestRender_Python(t *testing.T) {
	src, err := Render(widget(t), Python, Options{})
	if err != nil {
		t.Fatal(err)
	}
	s := string(src)
	for _, want := range []string{"# Code generated by be-ops authzgen", `WIDGET_VIEW: Final = "conformance.widget.view"`,
		`WIDGET_WIDGET: Final = "conformance.widget.widget"`, "CATALOG_JSON: Final = "} {
		if !strings.Contains(s, want) {
			t.Errorf("Python output lacks %q:\n%s", want, s)
		}
	}
	if py, err := exec.LookPath("python3"); err == nil {
		p := filepath.Join(t.TempDir(), "authzgen.py")
		os.WriteFile(p, src, 0o644)
		cmd := exec.Command(py, "-c", "import json,runpy; m=runpy.run_path('"+p+"'); json.loads(m['CATALOG_JSON'])['resource_types'][0]['view_key']")
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Errorf("python cannot load it: %v\n%s", err, out)
		}
	}
}

